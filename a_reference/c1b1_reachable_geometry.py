"""Induced coordinate tubes and direction constraints, without trajectory replay.

Conditional on the same successful KDK rounding map as the scalar induction.
No arbitrary oblique plane, exact angular conservation, or exact reachability
is assumed. See docs/active/C1B1_REACHABLE_GEOMETRY_V1.md for the induction.
"""
from fractions import Fraction as Q

from a_reference import c1b1_outer_bootstrap as O
from a_reference import c1b1_outer_bound as B

VERSION = 'c1b1-reachable-geometry-v1'


def cross(a, b):
    return (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2],
            a[0]*b[1]-a[1]*b[0])


def _ceil(x):
    return -(-x.numerator//x.denominator)


def _floor(x):
    return x.numerator//x.denominator


def _linear_interval(coefficients, box):
    intervals = [(min(c*x, c*y), max(c*x, c*y))
                 for c, (x, y) in zip(coefficients, box)]
    return (sum((v[0] for v in intervals), Q(0)),
            sum((v[1] for v in intervals), Q(0)))


def _exact_zero_axes(q, p):
    return tuple(k for k in range(3) if q[k] == p[k] == 0)


def _attach(run, geometry):
    """Internal: geometry must be generated by O.certify_outgoing_outer."""
    q0, p0, snapshot = O._state(run)
    if geometry['initial_state'] != snapshot:
        raise O.NotCertified('reachable geometry initial state mismatch')
    # q_k=P_k=0 means the two raw positions AND momenta coincide on that
    # axis. Impulse_k=0; identical masses and drift v2 preserve equality.
    zero_axes = _exact_zero_axes(q0, p0)
    position = tuple((x, x) for x in q0)
    kick_sum = Q(0)
    angular_cap = B.sqrt_up(O._norm2(cross(q0, p0)))
    records = []
    for shell in geometry['shells']:
        count, kcap = shell['max_steps'], shell['half_kick_cap']
        kick_sum += count*kcap
        momentum_change = 2*kick_sum
        # All full AND intermediate half momenta in this shell are within
        # this ball around P0: <=2 kicks per step, including shell exits.
        velocity = tuple((Q(0), Q(0)) if axis in zero_axes else
                         (O.ALPHA*(p-momentum_change)-B.UX,
                          O.ALPHA*(p+momentum_change)+B.UX)
                         for axis, p in enumerate(p0))
        entry_position = position
        position = tuple((lo+min(Q(0), count*vlow),
                          hi+max(Q(0), count*vhigh))
                         for (lo, hi), (vlow, vhigh) in zip(position, velocity))
        angular_cap += shell['angular_bohr_momentum']['total']
        radial_raw = min(2**96-1, _floor(shell['guard_b']/B.UX))
        box = tuple((max(-radial_raw, _ceil(lo/B.UX)),
                     min(radial_raw, _floor(hi/B.UX))) for lo, hi in position)
        if any(lo > hi for lo, hi in box):
            raise O.NotCertified('induced coordinate/radial enclosure is empty')
        # |q x P0| <= |q x P| + R |P-P0|,
        # q.P0 >= q.P - R |P-P0|. These retain the outward cone branch.
        direction_error = shell['guard_b']*momentum_change
        records.append({'shell_index': len(records), 'root_box': box,
                        'entry_position_intervals': entry_position,
                        'position_intervals': position,
                        'relative_displacement_intervals': velocity,
                        'momentum_change_norm_cap': momentum_change,
                        'relative_angular_norm_cap': angular_cap,
                        'initial_relative_momentum': p0,
                        'dot_initial_momentum_lower': shell['w_floor']-direction_error,
                        'cross_initial_momentum_norm_cap': angular_cap+direction_error,
                        'exact_zero_relative_axes': zero_axes,
                        'max_steps_in_shell': count})
    return {'version': VERSION,
            'scope': 'induction_coordinate_tube_and_outward_direction_projection',
            'exact_zero_relative_axes': zero_axes,
            'relative_coordinate_dimension': 3-len(zero_axes),
            'oblique_plane_preservation': 'not_assumed',
            'rounding_decision_completeness': 'not_proved',
            'shells': tuple(records)}


def certify_outgoing_reachable(run, p_cap):
    """Narrow the scalar projection using only its proved finite budgets."""
    geometry = O.certify_outgoing_outer(run, p_cap)
    projection = _attach(run, geometry)
    return geometry, projection


def exclude_direction_cell(box, constraint):
    """Prove a box disjoint from the cone; overlapping boxes remain live.

    This is a sufficient exclusion, never an exact feasible-set solver.
    Closed inequalities keep their equality boundary in the cover.
    """
    qbox = tuple((Q(lo)*B.UX, Q(hi)*B.UX) for lo, hi in box)
    p = constraint['initial_relative_momentum']
    _, dot_upper = _linear_interval(p, qbox)
    if dot_upper < constraint['dot_initial_momentum_lower']:
        return 'empty_outward_dot_intersection'
    cross_coefficients = ((Q(0), p[2], -p[1]),
                          (-p[2], Q(0), p[0]),
                          (p[1], -p[0], Q(0)))
    intervals = tuple(_linear_interval(c, qbox) for c in cross_coefficients)
    lower_squared = sum((Q(0) if lo <= 0 <= hi else min(lo*lo, hi*hi)
                         for lo, hi in intervals), Q(0))
    if lower_squared > constraint['cross_initial_momentum_norm_cap']**2:
        return 'empty_direction_cross_intersection'
    return None
